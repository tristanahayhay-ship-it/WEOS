const trendCycle: TrendDirection[] = ['up', 'stable', 'down']

const buildMetricGroups = (seed: number, name: string): Record<MetricGroupKey, MetricGroup> => {
  return metricGroupCatalog.reduce((acc, item, index) => {
    const base = 55 + ((seed * 7 + index * 5) % 38)
    const trend = trendCycle[(seed + index) % trendCycle.length]
    acc[item.key] = {
      key: item.key,
      title: item.title,
      score: base,
      trend,
      summary: `${item.title} của ${name} đang ${trend === 'up' ? 'mở rộng' : trend === 'down' ? 'chịu áp lực điều chỉnh' : 'ổn định trong biên cân bằng'}.`,
      metrics: [
        {
          label: 'Xung lực',
          value: base,
          unit: '/100',
          trend,
          change: Number((((seed + index) % 7) / 10).toFixed(1)),
        },
        {
          label: 'Nhịp 90 ngày',
          value: `${72 + ((seed + index * 3) % 21)}%`,
          trend: trend === 'stable' ? 'up' : trend,
          change: Number((((seed * 2 + index) % 9) / 10).toFixed(1)),
        },
        {
          label: 'Ghi chú AI',
          value: trend === 'up' ? 'Tăng tốc' : trend === 'down' ? 'Giảm tốc' : 'Giữ nhịp',
          trend,
          change: 0,
        },
      ],
    }
    return acc
  }, {} as Record<MetricGroupKey, MetricGroup>)
}

